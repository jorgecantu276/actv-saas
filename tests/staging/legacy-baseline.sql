--

CREATE FUNCTION public.limpiar_evidencias_antiguas() RETURNS void
    LANGUAGE plpgsql
    AS $$
BEGIN
  UPDATE inscripciones
  SET foto_evidencia = NULL
  WHERE kit_entregado = true 
    AND created_at < NOW() - INTERVAL '30 days'
    AND foto_evidencia IS NOT NULL;
END;
$$;


