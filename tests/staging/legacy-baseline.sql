--

CREATE FUNCTION public.borrar_archivo_storage_al_limpiar() RETURNS trigger
    LANGUAGE plpgsql
    AS $_$
DECLARE
  nombre_archivo TEXT;
BEGIN
  -- Si la foto pasa de tener URL a ser NULL (lo que hace nuestro cron)
  IF OLD.foto_evidencia IS NOT NULL AND NEW.foto_evidencia IS NULL THEN
    -- Extraemos el nombre del archivo de la URL pública
    nombre_archivo := substring(OLD.foto_evidencia from '[^/]+$');
    
    -- Lo eliminamos de la tabla interna de objetos de Supabase Storage
    DELETE FROM storage.objects 
    WHERE bucket_id = 'evidencias_kits' AND name = nombre_archivo;
  END IF;
  RETURN NEW;
END;
$_$;


